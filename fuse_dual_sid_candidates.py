def main() -> None:
    args = parse_args()
    ks = sorted(set(k for k in args.ks if k > 0))
    dedup_by_item = args.dedup_by_item.lower() == "true"
    targets = test_targets(args.test_csv)
    text_samples, text_schema = load_candidate_samples(args.text_candidates, targets, dedup_by_item)
    behavior_samples, behavior_schema = load_candidate_samples(args.behavior_candidates, targets, dedup_by_item)
    sample_ids = sorted(set(text_samples) | set(behavior_samples), key=item_sort_key)
    if not sample_ids:
        raise ValueError("No aligned candidate samples found.")

    union_metrics, union_rows = evaluate_union(sample_ids, text_samples, behavior_samples, targets, ks)
    min_rank_metrics, _, _ = fusion_metrics(
        sample_ids,
        text_samples,
        behavior_samples,
        targets,
        ks,
        args.lambda_text,
        args.k_rrf,
        "min_rank",
    )
    rrf_metrics, rrf_by_sample, _ = fusion_metrics(
        sample_ids,
        text_samples,
        behavior_samples,
        targets,
        ks,
        args.lambda_text,
        args.k_rrf,
        "rrf",
    )
    text_metrics = stream_metrics(text_samples, sample_ids, targets, ks)
    behavior_metrics = stream_metrics(behavior_samples, sample_ids, targets, ks)

    schema_report = {
        "text": {**text_schema, "preview": schema_preview(args.text_candidates, args.schema_sample_size)},
        "behavior": {**behavior_schema, "preview": schema_preview(args.behavior_candidates, args.schema_sample_size)},
        "dedup_by_item": dedup_by_item,
        "sample_alignment": {
            "text_samples": len(text_samples),
            "behavior_samples": len(behavior_samples),
            "union_samples": len(sample_ids),
            "text_only_samples": len(set(text_samples) - set(behavior_samples)),
            "behavior_only_samples": len(set(behavior_samples) - set(text_samples)),
        },
    }
    report = {
        "inputs": {
            "text_candidates": args.text_candidates.as_posix(),
            "behavior_candidates": args.behavior_candidates.as_posix(),
            "test_csv": args.test_csv.as_posix(),
            "text_name": args.text_name,
            "behavior_name": args.behavior_name,
        },
        "outputs": {
            "dual_fused_candidates_jsonl": (args.out_dir / "dual_fused_candidates.jsonl").as_posix(),
            "dual_fused_candidates_flat_jsonl": (args.out_dir / "dual_fused_candidates_flat.jsonl").as_posix(),
            "dual_fusion_metrics_csv": (args.out_dir / "dual_fusion_metrics.csv").as_posix(),
            "per_sample_dual_fusion_csv": (args.out_dir / "per_sample_dual_fusion.csv").as_posix(),
            "schema_report_json": (args.out_dir / "schema_report.json").as_posix(),
            "report_md": (args.out_dir / "report.md").as_posix(),
        },
        "topk": ks,
        "rrf": {
            "lambda_text": args.lambda_text,
            "k_rrf": args.k_rrf,
            "rank_is_1_based": True,
        },
        "schema": schema_report,
        "text_stream": text_metrics,
        "behavior_stream": behavior_metrics,
        "union_recall": union_metrics,
        "min_rank_fusion": min_rank_metrics,
        "rrf_fusion": rrf_metrics,
        "notes": {
            "leakage_policy": "target item is used only for metrics; fusion uses only candidate item ids and ranks",
            "primary_fused_jsonl": "dual_fused_candidates.jsonl is written in a rerank.py-compatible nested format",
        },
    }

    args.out_dir.mkdir(parents=True, exist_ok=True)
    write_fused_outputs(args.out_dir, sample_ids, text_samples, behavior_samples, targets, rrf_by_sample, union_rows)
    write_json(args.out_dir / "dual_fusion_report.json", report)
    write_json(args.out_dir / "schema_report.json", schema_report)
    write_csv(args.out_dir / "dual_fusion_metrics.csv", ["section", "metric", "value"], metrics_rows(report))
    write_markdown_report(args.out_dir, report)

    print(f"Wrote fused candidates: {args.out_dir / 'dual_fused_candidates.jsonl'}")
    print(f"Wrote fusion report: {args.out_dir / 'dual_fusion_report.json'}")
    print(f"Wrote schema report: {args.out_dir / 'schema_report.json'}")
    print(
        "Dual fusion summary: "
        f"text_HR@20={text_metrics.get('hr@20', NOT_AVAILABLE)} "
        f"behavior_HR@20={behavior_metrics.get('hr@20', NOT_AVAILABLE)} "
        f"union_HR@20={union_metrics.get('union_hit@20', NOT_AVAILABLE)} "
        f"minrank_HR@20={min_rank_metrics.get('hr@20', NOT_AVAILABLE)} "
        f"rrf_HR@20={rrf_metrics.get('hr@20', NOT_AVAILABLE)}"
    )


if __name__ == "__main__":
    main()
